# -*- coding: utf-8 -*-
"""v52: master results table and a single definition for every number.

Fixes the four inconsistencies the audit found:
  * the pooled subject correlation keyed subjects by bare name, so gal/SEED/2b
    subjects with the same id collided (27 instead of 36).  Keys are (ds, subj).
  * dR2 is *defined* as the per-cell excess, and both the median of the per-cell
    values and the difference of the medians are reported so the two conventions
    can never be confused again.
  * the correction loss L is defined per cell on the same evaluation window as
    everything else, BA(lambda=0) - BA(lambda=1); the mean and the median over
    cells are both reported.
  * all BA(lambda) curves are subject-level: cells are averaged within subject
    first, then bootstrapped over subjects.

Writes:
  results/master_cells.csv   one row per cell, all quantities
  results/master_stats.md    every number quoted in the paper, with its rule
"""
import os
import sys
import numpy as np
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pv8_common as C
from pv8_causal import scores

RES = os.path.join(HERE, "results")
CSV = os.path.join(RES, "master_cells.csv")
MD = os.path.join(RES, "master_stats.md")
M = 15
NPERM = 500
LAMS = (0.0, 0.1, 0.25, 0.5, 0.75, 1.0)
SOURCE_ONLY = ("euc", "csp", "de", "Ftime", "pow")
L = []


def say(s=""):
    L.append(str(s))
    with open(MD, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")


def pairs(ds):
    ps = C.all_pairs((ds,))
    if ds == "gal":
        ps = [p for p in ps
              if int(p["meta"]["seq"].split(">")[0]) < int(p["meta"]["seq"].split(">")[1])]
    return [p for p in ps if p["rep"] in SOURCE_ONLY]


def r2_of(idx, Y):
    x = idx - idx.mean()
    xc = x / (np.linalg.norm(x) + 1e-12)
    Yc = Y - Y.mean(0)
    den = np.linalg.norm(Yc, axis=0) + 1e-12
    return float(np.mean((xc @ Yc / den) ** 2))


def cell(A, ya, Bt, yb, rng):
    clf = C.make("lda").fit(A, ya)
    classes = np.asarray(clf.classes_)
    K = len(classes)
    W = C.linear_weights(clf, A.shape[1], K)
    F = np.eye(K) - np.ones((K, K)) / K
    muA = A.mean(0)
    n = len(yb)
    if n < 2 * M:
        return None
    S0 = scores(Bt, W, np.asarray(clf.intercept_, float).ravel(), K)
    blocks = [(a, min(a + M, n)) for a in range(0, n, M)]
    D = np.array([F @ (W @ (Bt[a:b].mean(0) - muA)) for a, b in blocks])
    B = len(D)
    if B < 4:
        return None
    row = dict(B=B, dnrm=float(np.mean(np.linalg.norm(D, axis=1))))
    idx = np.arange(B)
    row["R2"] = r2_of(idx, D)
    null = np.array([r2_of(idx, D[rng.permutation(B)]) for _ in range(NPERM)])
    row["R2null"] = float(null.mean())
    row["dR2"] = row["R2"] - row["R2null"]
    row["R2_4"] = r2_of(np.arange(4), D[:4]) if B >= 4 else np.nan
    Dc = D - D.mean(0)
    row["lag1"] = float(np.mean([np.corrcoef(Dc[:-1, k], Dc[1:, k])[0, 1]
                                 if np.std(Dc[:, k]) > 1e-12 else 0.0 for k in range(K)]))
    for lam in LAMS:
        S = S0.copy()
        for i, (a, b) in enumerate(blocks):
            if i == 0:
                continue
            S[a:b] = S0[a:b] - lam * D[:i].mean(0)[None, :]
        row["ba%.2f" % lam] = C.ba(yb[M:], classes[np.argmax(S[M:], 1)])
    row["loss"] = row["ba0.00"] - row["ba1.00"]
    return row


def boot_ci(v, reps=6000):
    v = np.asarray(v, float)
    rs = np.random.RandomState(0)
    bs = np.array([np.mean(rs.choice(v, len(v))) for _ in range(reps)])
    return float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))


def main():
    rng = np.random.RandomState(0)
    rows = []
    for ds in ("gal", "seed", "2b", "2a", "ner"):
        for p in pairs(ds):
            r = cell(p["A"], p["ya"], p["B"], p["yb"], rng)
            if r:
                r.update(ds=ds, subj=p["subj"], pid=p["pid"])
                rows.append(r)
    keys = ["ds", "subj", "pid", "B", "R2", "R2null", "dR2", "R2_4", "lag1",
            "dnrm", "loss"] + ["ba%.2f" % l for l in LAMS]
    with open(CSV, "w", encoding="utf-8") as f:
        f.write(",".join(keys) + "\n")
        for r in rows:
            f.write(",".join([r["ds"], r["subj"], r["pid"]] +
                             ["%d" % r["B"]] +
                             ["%.4f" % r[k] for k in keys[4:]]) + "\n")

    say("# master statistics (generated by pv8_master.py)")
    say("")
    say("Rules used here and nowhere else:")
    say("- dR2 is computed per cell as R2 - mean(R2 under 500 block-order permutations).")
    say("- The table reports the median of the per-cell dR2 *and* the difference of")
    say("  the medians (R2 - R2null); the two differ and both are legitimate.")
    say("- loss is per cell BA(lambda=0) - BA(lambda=1); mean and median over cells.")
    say("- All BA(lambda) figures aggregate cells within subject first, then bootstrap")
    say("  over subjects (6,000 resamples).")
    say("")

    say("## per dataset")
    say("")
    say("| ds | cells | subjects | B | R2 med | R2null med | dR2 med | dR2 (diff of med) | loss mean | loss med | lag1 |")
    say("|---|---|---|---|---|---|---|---|---|---|---|")
    for ds in ("gal", "seed", "2b", "2a", "ner"):
        sel = [r for r in rows if r["ds"] == ds]
        if not sel:
            continue
        say("| %s | %d | %d | %.0f | %.3f | %.3f | %+.3f | %+.3f | %+.4f | %+.4f | %+.2f |"
            % (ds, len(sel), len({r["subj"] for r in sel}), np.median([r["B"] for r in sel]),
               np.median([r["R2"] for r in sel]), np.median([r["R2null"] for r in sel]),
               np.median([r["dR2"] for r in sel]),
               np.median([r["R2"] for r in sel]) - np.median([r["R2null"] for r in sel]),
               np.mean([r["loss"] for r in sel]), np.median([r["loss"] for r in sel]),
               np.median([r["lag1"] for r in sel])))
    say("")

    say("## correction-strength response, subject level")
    say("")
    say("| ds | " + " | ".join("lam=%.2f" % l for l in LAMS) + " | D_i<0 subjects |")
    say("|---|" + "---|" * (len(LAMS) + 1))
    for ds in ("gal", "seed", "2b", "2a", "ner"):
        sel = [r for r in rows if r["ds"] == ds]
        if not sel:
            continue
        by = {}
        for r in sel:
            by.setdefault(r["subj"], []).append(r)
        cells = []
        for l in LAMS:
            per_subj = [np.mean([r["ba%.2f" % l] for r in v]) for v in by.values()]
            cells.append("%.4f" % np.mean(per_subj))
        Di = [np.mean([r["ba1.00"] for r in v]) - np.mean([r["ba0.00"] for r in v])
              for v in by.values()]
        say("| %s | %s | %d/%d |" % (ds, " | ".join(cells),
                                     sum(1 for d in Di if d < 0), len(Di)))
    say("")
    say("D_i = BA(lambda=1) - BA(lambda=0) within subject, then averaged.")
    for ds in ("gal", "seed", "2b", "2a", "ner"):
        sel = [r for r in rows if r["ds"] == ds]
        if not sel:
            continue
        by = {}
        for r in sel:
            by.setdefault(r["subj"], []).append(r)
        Di = [np.mean([r["ba1.00"] for r in v]) - np.mean([r["ba0.00"] for r in v])
              for v in by.values()]
        lo, hi = boot_ci(Di)
        say("- %s: D = %+.4f [%+.4f, %+.4f], negative in %d of %d subjects"
            % (ds, np.mean(Di), lo, hi, sum(1 for d in Di if d < 0), len(Di)))
    say("")

    say("## trend versus loss")
    say("")
    for ds in ("gal", "seed", "2b", "2a", "ner"):
        sel = [r for r in rows if r["ds"] == ds]
        by = {}
        for r in sel:
            by.setdefault(r["subj"], []).append(r)
        if len(by) < 5:
            continue
        d = [np.median([r["dR2"] for r in v]) for v in by.values()]
        l = [np.median([r["loss"] for r in v]) for v in by.values()]
        rho, p = stats.spearmanr(d, l)
        say("- %s: %d subjects, rho(dR2, loss) = %+.3f, p = %.3f" % (ds, len(by), rho, p))
    # pooled with dataset fixed effect: centre within dataset
    pooled = []
    for ds in ("gal", "seed", "2b"):
        sel = [r for r in rows if r["ds"] == ds]
        by = {}
        for r in sel:
            by.setdefault((ds, r["subj"]), []).append(r)
        d = np.array([np.median([r["dR2"] for r in v]) for v in by.values()])
        l = np.array([np.median([r["loss"] for r in v]) for v in by.values()])
        pooled.append((d - d.mean(), l - l.mean()))
    D = np.concatenate([p[0] for p in pooled])
    Lv = np.concatenate([p[1] for p in pooled])
    rho = stats.spearmanr(D, Lv)[0]
    rs = np.random.RandomState(0)
    bs = []
    for _ in range(4000):
        idx = rs.choice(len(D), len(D))
        if np.std(D[idx]) > 1e-12 and np.std(Lv[idx]) > 1e-12:
            bs.append(stats.spearmanr(D[idx], Lv[idx])[0])
    say("- pooled gal+seed+2b, %d subjects, within-dataset centred: rho = %+.3f [%+.3f, %+.3f]"
        % (len(D), rho, np.percentile(bs, 2.5), np.percentile(bs, 97.5)))
    say("")

    say("## gal sensitivity")
    say("")
    gal = [r for r in rows if r["ds"] == "gal"]
    by = {}
    for r in gal:
        by.setdefault(r["subj"], []).append(r)
    subs = sorted(by)
    say("| subject | R2 | dR2 | R2(first 4) | loss |")
    say("|---|---|---|---|---|")
    for s in subs:
        v = by[s]
        say("| %s | %.3f | %+.3f | %.3f | %+.3f |"
            % (s, np.median([r["R2"] for r in v]), np.median([r["dR2"] for r in v]),
               np.median([r["R2_4"] for r in v]), np.median([r["loss"] for r in v])))
    d_all = np.array([np.median([r["dR2"] for r in by[s]]) for s in subs])
    l_all = np.array([np.median([r["loss"] for r in by[s]]) for s in subs])
    d_4 = np.array([np.median([r["R2_4"] for r in by[s]]) for s in subs])
    say("")
    say("- rho(dR2_5blocks, loss) = %+.3f" % stats.spearmanr(d_all, l_all)[0])
    say("- rho(R2_4blocks, loss) = %+.3f" % stats.spearmanr(d_4, l_all)[0])
    loo = []
    for i in range(len(subs)):
        m = np.ones(len(subs), bool)
        m[i] = False
        loo.append(stats.spearmanr(d_all[m], l_all[m])[0])
    say("- leave-one-subject-out rho: min %+.3f max %+.3f" % (min(loo), max(loo)))
    print("done", MD)


if __name__ == "__main__":
    main()
